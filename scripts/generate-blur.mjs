// Generates tiny blurred previews for the bundled product images so they
// appear instantly while the full image loads. Run: node scripts/generate-blur.mjs
import sharp from "sharp"
import { readdir, writeFile } from "node:fs/promises"

const dir = "public/images"
const files = (await readdir(dir)).filter((f) => /\.(webp|png|jpe?g)$/.test(f) && !f.startsWith("alicia-lux-"))
const entries = await Promise.all(
  files.map(async (f) => {
    const buf = await sharp(`${dir}/${f}`).resize(16, 16, { fit: "inside" }).blur(1).webp({ quality: 40 }).toBuffer()
    return `  "/images/${f}": "data:image/webp;base64,${buf.toString("base64")}",`
  })
)
await writeFile(
  "src/lib/blur-data.ts",
  `// Generated by scripts/generate-blur.mjs — do not edit by hand.\nexport const blurData: Record<string, string> = {\n${entries.join("\n")}\n}\n`
)
console.log(`✓ ${files.length} blur placeholders`)
